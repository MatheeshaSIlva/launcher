#!/usr/bin/env python3
"""Generate the engine's hidden statusbar set. No downloads or third-party modules.

Coordinates are StatusBarView points at u=1, cy=0; boxes retain its slot alignment.
Run from any directory, optionally giving an output path. Output is compact UTF-8.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "engine/src/main/assets/icons/statusbar.json"
SOURCE = "app/src/main/java/dev/launcher/app/statusbar/StatusBarView.kt"
FAINT = 77 / 255


def number(value):
    return format(round(value, 6) + 0.0, ".6f").rstrip("0").rstrip(".") or "0"


def point(x, y):
    return f"{number(x)} {number(y)}"


def polar(cx, cy, radius, angle):
    return cx + radius * math.cos(angle), cy + radius * math.sin(angle)


def arc(radius, large, sweep, end):
    return f"A{number(radius)} {number(radius)} 0 {large} {sweep} {point(*end)}"


def polygon(points):
    return "M" + "L".join(point(x, y) for x, y in points) + "Z"


def rounded_bar(x, bottom, height):
    # drawCell :1342-1354: width 3, radius 1, gap 2.2, heights 4.4/6.8/9.2/11.7.
    top, right = bottom - height, x + 3
    return (f"M{point(x + 1, top)}L{point(right - 1, top)}" + arc(1, 0, 1, (right, top + 1)) +
            f"L{point(right, bottom - 1)}" + arc(1, 0, 1, (right - 1, bottom)) +
            f"L{point(x + 1, bottom)}" + arc(1, 0, 1, (x, bottom - 1)) +
            f"L{point(x, top + 1)}" + arc(1, 0, 1, (x + 1, top)) + "Z")


def fan(outer, band):
    # drawWifi :1421-1434; slot :797,881. Fan origin is (8.5, cy + 5.6).
    start, end = math.radians(225), math.radians(315)
    inner = outer - band
    path = "M" + point(*polar(8.5, 5.6, outer, start))
    path += arc(outer, 0, 1, polar(8.5, 5.6, outer, end))
    if inner > 0.5:
        path += "L" + point(*polar(8.5, 5.6, inner, end))
        path += arc(inner, 0, 0, polar(8.5, 5.6, inner, start))
    else:
        path += "L8.5 5.6"
    return path + "Z"


def moon_geometry():
    """Circle intersections and the two retained boundary arcs (angles in radians)."""
    # drawMoon :1371-1377; moonSlot :790,840: r=6.2, cut=(.55r,-.45r), cut r=.85r.
    radius = 6.2
    cx, cy, cut_radius = 0.55 * radius, -0.45 * radius, 0.85 * radius
    distance = math.hypot(cx, cy)
    along = (radius**2 - cut_radius**2 + distance**2) / (2 * distance)
    phi = math.atan2(cy, cx)
    theta = math.acos(along / radius)
    start = polar(0, 0, radius, phi + theta)
    end = polar(0, 0, radius, phi - theta)
    return radius, (cx, cy, cut_radius), start, end


def moon():
    radius, (_, _, cut_radius), start, end = moon_geometry()
    # Long clockwise outer arc; short counterclockwise cut arc, inside the original circle.
    return "M" + point(*start) + arc(radius, 1, 1, end) + arc(cut_radius, 0, 0, start) + "Z"


def glyph(box, paths, source, level=None):
    return {"src": f"{SOURCE}:{source}", "box": box,
            "layers": [{"d": path, "a": 1 if level is None or i < level else FAINT}
                       for i, path in enumerate(paths)]}


def build():
    icons = {}
    for level in range(4):
        icons[f"wifi.{level}"] = glyph([0, -5.6, 17, 11.2],
            [fan(r, b) for r, b in zip((3.4, 7.4, 11.2), (3.4, 2.6, 2.6))],
            "1421-1434 drawWifi; 797,881 placement", level)
    for level in range(5):
        icons[f"cell.{level}"] = glyph([0, -5.85, 18.6, 11.7],
            [rounded_bar(i * 5.2, 5.85, h) for i, h in enumerate((4.4, 6.8, 9.2, 11.7))],
            "1333-1357 drawCell; 887-892 slot", level)
    icons["moon"] = glyph([-6.2, -6.2, 12.4, 12.4], [moon()], "1371-1377 drawMoon; 790,840 placement")
    # drawBolt :1380-1391; :794 centre at left+3.6, :874 slot width 7.6.
    # The box is the slot, preserving the polygon's -0.2 offset from its midpoint.
    bolt = [(3.6 + 9*x, 9*y) for x, y in ((.12, -.5), (-.3, .08), (-.02, .08),
                                                       (-.12, .5), (.3, -.08), (.02, -.08))]
    icons["bolt"] = glyph([0, -4.5, 7.6, 9], [polygon(bolt)], "1380-1391 drawBolt; 794,874 placement")
    # drawPlane :1394-1417; drawCell :1338 centres at left+8.4, s=8.4.
    plane = [(8.4*x, 8.4*y) for x, y in ((1, 0), (.75, -.12), (.15, -.12), (-.25, -.8),
        (-.45, -.8), (-.2, -.12), (-.65, -.12), (-.85, -.38), (-1, -.38), (-.85, 0),
        (-1, .38), (-.85, .38), (-.65, .12), (-.2, .12), (-.45, .8), (-.25, .8), (.15, .12), (.75, .12))]
    icons["airplane"] = glyph([-8.4, -6.72, 16.8, 13.44], [polygon(plane)], "1394-1417 drawPlane; 1338 placement")
    return {"name": "Status bar", "listed": False, "icons": icons}


def encoded():
    # No newline: this repo's text=auto / Windows autocrlf must not change the generated bytes on checkout.
    return json.dumps(build(), ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=OUTPUT)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(encoded())


if __name__ == "__main__":
    main()
